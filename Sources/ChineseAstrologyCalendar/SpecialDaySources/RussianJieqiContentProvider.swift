import Foundation

// MARK: - RussianJieqiContentProvider

/// Russian-language content for `JieqiSource`.
///
/// Supplies Russian names and seasonal health notes for every `Jieqi` case.
///
/// ```swift
/// let source = JieqiSource(contentProvider: RussianJieqiContentProvider())
/// ```
public struct RussianJieqiContentProvider: JieqiContentProvider {

  public init() {}

  public func name(for jieqi: Jieqi) -> String {
    switch jieqi {
    case .startOfSpring:      return "Начало весны"
    case .rainWater:          return "Дождевая вода"
    case .awakeningOfInsects: return "Пробуждение насекомых"
    case .springEquinox:      return "Весеннее равноденствие"
    case .clearAndBright:     return "Ясность и чистота (Цинмин)"
    case .grainRain:          return "Хлебные дожди"
    case .startOfSummer:      return "Начало лета"
    case .grainBuds:          return "Малое изобилие"
    case .grainInEar:         return "Колошение хлебов"
    case .summerSolstice:     return "Летнее солнцестояние"
    case .minorHeat:          return "Малая жара"
    case .majorHeat:          return "Большая жара"
    case .startOfAutumn:      return "Начало осени"
    case .endOfHeat:          return "Конец жары"
    case .whiteDew:           return "Белые росы"
    case .autumnEquinox:      return "Осеннее равноденствие"
    case .coldDew:            return "Холодные росы"
    case .frostDescent:       return "Выпадение инея"
    case .startOfWinter:      return "Начало зимы"
    case .minorSnow:          return "Малые снега"
    case .majorSnow:          return "Большие снега"
    case .winterSolstice:     return "Зимнее солнцестояние"
    case .minorCold:          return "Малые холода"
    case .majorCold:          return "Большие холода"
    }
  }

  public func detail(for jieqi: Jieqi) -> String {
    switch jieqi {
    case .startOfSpring:
      return "В начале весны питайте печень и берегите ян: ложитесь и вставайте рано, разминайте тело, чтобы поднять ян-ци, и сохраняйте бодрое расположение духа."
    case .rainWater:
      return "В сезон дождевой воды сырость усиливается: укрепляйте селезёнку и выводите влагу, ешьте лёгкую пищу, держите живот в тепле и избегайте переохлаждения."
    case .awakeningOfInsects:
      return "На Пробуждение насекомых ян-ци поднимается: освобождайте застой печени и упорядочивайте ци, сохраняйте душевное спокойствие и умеренно двигайтесь на воздухе."
    case .springEquinox:
      return "На весеннее равноденствие инь и ян уравновешены: гармонизируйте ци и кровь, соблюдайте режим и избегайте переутомления ради согласия инь и ян."
    case .clearAndBright:
      return "На Цинмин энергия печени в избытке: снимайте застой печени, гуляйте на природе, чтобы облегчить настроение, и избегайте бурных радостей и печалей."
    case .grainRain:
      return "На хлебные дожди сырость велика: выводите влагу и укрепляйте селезёнку, массируйте точки селезёнки и желудка, а пищу выбирайте тёплую и легко усваиваемую."
    case .startOfSummer:
      return "В начале лета энергия сердца в избытке: питайте сердце и успокаивайте дух, сохраняйте душевное равновесие и отдыхайте недолго в полдень."
    case .grainBuds:
      return "На Малое изобилие нарастают сырость и жар: очищайте жар и выводите влагу, ешьте лёгкую нежирную пищу и держите кожу чистой, предупреждая экзему."
    case .grainInEar:
      return "На колошение хлебов зной усиливается: успокаивайте сердце и спасайтесь от жары, двигайтесь умеренно, избегая обильного пота, чтобы не истощить энергию сердца."
    case .summerSolstice:
      return "На летнее солнцестояние ян-ци в зените: успокаивайте сердце и питайте инь, избегайте полуденного зноя и отдыхайте в полдень, восстанавливая дух сердца."
    case .minorHeat:
      return "На Малую жару зной поднимается волнами: спасайтесь от жары и укрепляйте ци, проветривайте помещение и не злоупотребляйте прохладой, чтобы не повредить ян-ци."
    case .majorHeat:
      return "Большая жара — самое жаркое время года: очищайте жар и укрепляйте ци, поддерживайте селезёнку, восполняйте жидкость в меру и остерегайтесь теплового удара."
    case .startOfAutumn:
      return "В начале осени питайте лёгкие и увлажняйте сухость: ложитесь и вставайте рано, восполняйте влагу и берегите лёгкие от осенней сухости."
    case .endOfHeat:
      return "На Конец жары зной отступает: питайте лёгкие и берегите инь, учитывайте перепады температуры утром и вечером и вовремя одевайтесь теплее."
    case .whiteDew:
      return "На Белые росы температура падает: питайте инь и увлажняйте сухость, держите ноги в тепле и не ходите босиком по холодному полу, чтобы не повредить энергию почек."
    case .autumnEquinox:
      return "На осеннее равноденствие инь и ян вновь уравновешиваются: питайте лёгкие и собирайте ци, сохраняйте душевное спокойствие и избегайте чрезмерной печали."
    case .coldDew:
      return "На Холодные росы климат сухой: увлажняйте лёгкие и восполняйте жидкости тела, держите тепло, особенно шею и лодыжки, предупреждая проникновение холода."
    case .frostDescent:
      return "На Выпадение инея энергия инь усиливается: укрепляйте печень и почки, держите тепло и умеренно используйте укрепляющее питание, готовясь к зиме."
    case .startOfWinter:
      return "В начале зимы питайте почки и сберегайте силы: ложитесь рано, вставайте поздно, избегайте холода и держитесь тепла, накапливая цзин-ци на зиму."
    case .minorSnow:
      return "На Малые снега холод усиливается: согревайте почки и поддерживайте ян, держите тепло в спине и пояснице и сокращайте интенсивные занятия на улице."
    case .majorSnow:
      return "На Большие снега стужа сковывает землю: укрепляйте почки и основу здоровья; можно парить ноги, чтобы изгнать холод и согреться."
    case .winterSolstice:
      return "На зимнее солнцестояние инь в зените, а ян зарождается: укрепляйте почки и сберегайте силы, ложитесь рано и вставайте поздно, спокойно накапливая цзин-ци."
    case .minorCold:
      return "Малые холода — самая холодная пора года: тепло укрепляйте ян почек, защищайтесь от ветра и держите тепло, избегая простуды, ранящей почки."
    case .majorCold:
      return "На Большие холода стужа достигает предела: укрепляйте энергию почек, держите в тепле всё тело и делайте умеренную согревающую гимнастику в помещении."
    }
  }

  public var category: String { "Солнечный сезон (цзеци)" }
}
